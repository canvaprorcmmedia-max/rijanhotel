-- Rancangan skema awal Hotel Rijan.
-- Tinjau dan uji di proyek Supabase terpisah sebelum dipakai produksi.
create table if not exists public.rooms (
  id text primary key,
  name text not null,
  description text,
  price integer not null default 0 check (price >= 0),
  capacity text,
  view_description text,
  features jsonb not null default '[]'::jsonb,
  image_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.facilities (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  icon text,
  sort_order integer not null default 0,
  is_published boolean not null default false
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  sort_order integer not null default 0,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.hotel_settings (
  id integer primary key default 1 check (id = 1),
  hotel_name text not null default 'Hotel Rijan',
  address text,
  whatsapp_number text,
  email text,
  updated_at timestamptz not null default now()
);

-- Aktifkan RLS. Kebijakan tulis/admin perlu dibuat setelah menentukan
-- identitas admin yang berwenang. Jangan membuka akses tulis untuk anon.
alter table public.rooms enable row level security;
alter table public.facilities enable row level security;
alter table public.gallery enable row level security;
alter table public.hotel_settings enable row level security;

-- Kebijakan baca publik hanya untuk data yang dipublikasikan.
create policy "Public can read published rooms" on public.rooms
  for select to anon, authenticated using (is_published = true);
create policy "Public can read published facilities" on public.facilities
  for select to anon, authenticated using (is_published = true);
create policy "Public can read published gallery" on public.gallery
  for select to anon, authenticated using (is_published = true);
create policy "Public can read hotel settings" on public.hotel_settings
  for select to anon, authenticated using (true);

